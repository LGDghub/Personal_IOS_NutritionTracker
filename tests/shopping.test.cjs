testAssert.equal(normalize(updated).shoppingItems[0].quantity,4);
testAssert.equal(normalize(updated).shoppingDiscounts['2026-10-12'].value,10);
updated.shoppingItems[0].unit='nonsense';testAssert.throws(()=>normalize(updated));
